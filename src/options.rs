/// Game controller button for `--button-to-touch=` option.
#[derive(Copy, Clone, Hash, PartialEq, Eq, Debug)]
pub enum Button {
    DPadLeft,
    DPadUp,
    DPadRight,
    DPadDown,
    Start,
    A,
    B,
    X,
    Y,
    LeftShoulder,
}

/// Selects the bounded, package-focused Level 3 provenance probes. These are
/// deliberately separate from the general flight recorder: ordinary apps do
/// not pay for the focused campaign, and the Swordigo class-availability
/// experiment cannot be confused with passive observation.
#[derive(Copy, Clone, Debug, Default, Eq, PartialEq)]
pub enum DiagnosticCampaign {
    #[default]
    Off,
    Level3Provenance,
    SwordigoUIDocument,
}

impl DiagnosticCampaign {
    pub fn is_enabled(self) -> bool {
        self != Self::Off
    }

    pub fn is_intervention(self) -> bool {
        self == Self::SwordigoUIDocument
    }

    pub fn as_str(self) -> &'static str {
        match self {
            Self::Off => "off",
            Self::Level3Provenance => "level3-provenance",
            Self::SwordigoUIDocument => "swordigo-uidocument",
        }
    }
}

/// Struct containing all user-configurable options.
#[derive(Clone)]
pub struct Options {
    pub diagnostics: bool,
    pub diagnostic_campaign: DiagnosticCampaign,
    pub diagnostic_watch_addresses: Vec<u32>,
    pub fullscreen: bool,
    pub device_family: Option<DeviceFamily>,
    pub initial_orientation: DeviceOrientation,
    pub scale_hack: NonZeroU32,
    pub deadzone: f32,
    pub analog_stick_tilt_controls: bool,
    pub x_tilt_range: f32,
    pub y_tilt_range: f32,
    pub x_tilt_offset: f32,
    pub y_tilt_offset: f32,
    pub button_to_touch: HashMap<Button, (f32, f32)>,
    pub dpad_to_touch: Option<(f32, f32, f32, f32)>,
    pub stick_to_touch: Option<(f32, f32, f32, f32)>,
    pub stabilize_virtual_cursor: Option<(f32, f32)>,
    pub gles1_implementation: Option<GLESImplementation>,
    pub direct_memory_access: bool,
    pub gdb_listen_addrs: Option<Vec<SocketAddr>>,
    pub preferred_languages: Option<Vec<String>>,
    pub headless: bool,
    pub print_fps: bool,
    pub fps_limit: Option<f64>,
    pub force_composition: bool,
    pub network_access: bool,
    pub popup_errors: bool,
    pub dumping_options: DumpingOptions,
    pub dumping_file: PathBuf,
    pub ignore_gl_errors: bool,
    pub zero_stack_after_guest_to_host_call: Option<u32>,
}

